/** 그날 매장이 쉬는지: 쉬는 요일(0=월 ~ 6=일)이거나, 공휴일 휴무 매장의 공휴일 */
export function isClosedDay(
  date: Date,
  dateKey: string,
  store: { closedWeekdays: number[]; closedOnHolidays: boolean },
) {
  return (
    store.closedWeekdays.includes((date.getDay() + 6) % 7) ||
    (store.closedOnHolidays && !!HOLIDAYS[dateKey])
  )
}
