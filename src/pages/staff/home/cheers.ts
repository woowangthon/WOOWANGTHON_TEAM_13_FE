// 알바 홈 오늘 근무 카드의 응원 한 줄 — 담당: 민지
// 문구는 기획 그대로 20개 (바꾸지 않는다). 날짜로 하나를 골라 하루 동안 같고 날마다 바뀐다

export const CHEERS = [
  '오늘도 힘내요',
  '잘하고 있어요',
  '천천히 해요',
  '물 자주 드세요',
  '오늘도 반가워요',
  '오늘도 고마워요',
  '웃으며 시작해요',
  '무리하지 마세요',
  '좋은 하루 돼요',
  '든든하게 가요',
  '차근차근 해봐요',
  '마감까지 힘내요',
  '함께라 든든해요',
  '크루가 함께해요',
  '쉬엄쉬엄 해요',
  '정성껏 해봐요',
  '오늘도 빛나요',
  '어깨 펴고 가요',
  '웃는 하루 돼요',
  '오늘도 수고해요',
] as const

/** 그날의 응원 문구: 1970-01-01 부터 며칠째인지로 고른다 (같은 날이면 늘 같고, 다음 날은 다음 문구) */
export function cheerOf(date: Date) {
  const day = Math.floor(
    Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / (24 * 60 * 60 * 1000),
  )
  return CHEERS[day % CHEERS.length]
}
